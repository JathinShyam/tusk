#!/usr/bin/env bash
set -euo pipefail

: "${TUSK_MIGRATE_PASSWORD:?TUSK_MIGRATE_PASSWORD is required}"
: "${TUSK_APP_PASSWORD:?TUSK_APP_PASSWORD is required}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tusk_migrator') THEN
    CREATE ROLE tusk_migrator LOGIN PASSWORD '${TUSK_MIGRATE_PASSWORD}'
      NOSUPERUSER NOCREATEDB NOCREATEROLE BYPASSRLS;
  ELSE
    ALTER ROLE tusk_migrator WITH LOGIN PASSWORD '${TUSK_MIGRATE_PASSWORD}' BYPASSRLS;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tusk_app') THEN
    CREATE ROLE tusk_app LOGIN PASSWORD '${TUSK_APP_PASSWORD}'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
  ELSE
    ALTER ROLE tusk_app WITH LOGIN PASSWORD '${TUSK_APP_PASSWORD}' NOBYPASSRLS;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tusk_cron') THEN
    CREATE ROLE tusk_cron NOLOGIN
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
  END IF;
END
\$\$;
EOSQL
